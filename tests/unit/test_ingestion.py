class TestAPIIngestion:
    """Tests for APIIngestion."""

    def test_extract_valid_response(self):
        """Valid JSON response with records returns a DataFrame."""
        mock_response = MagicMock()
        mock_response.status_code = 200
        mock_response.json.return_value = {
            "dataset": "transactions",
            "records": [
                {"transaction_id": "TXN-001", "amount": 100.0},
                {"transaction_id": "TXN-002", "amount": 200.0},
            ],
        }

        with patch("src.ingestion.api_ingestion.requests.get", return_value=mock_response):
            adapter = APIIngestion(url="http://test.example.com/api/data")
            df = adapter.extract()

        assert isinstance(df, pd.DataFrame)
        assert len(df) == 2
        assert "transaction_id" in df.columns

    def test_source_type(self):
        """source_type property returns 'api'."""
        adapter = APIIngestion(url="http://test.example.com/api")
        assert adapter.source_type == "api"

    def test_http_error_raises_ingestion_error(self):
        """Non-200 HTTP status raises IngestionError."""
        mock_response = MagicMock()
        mock_response.status_code = 500
        mock_response.text = "Internal Server Error"

        with patch("src.ingestion.api_ingestion.requests.get", return_value=mock_response):
            adapter = APIIngestion(url="http://test.example.com/api/data")
            with pytest.raises(IngestionError, match="HTTP 500"):
                adapter.extract()

    def test_connection_error_raises_ingestion_error(self):
        """Network failure raises IngestionError."""
        import requests as req

        with patch("src.ingestion.api_ingestion.requests.get",
                   side_effect=req.exceptions.ConnectionError("refused")):
            adapter = APIIngestion(url="http://unreachable.example.com/api")
            with pytest.raises(IngestionError, match="connection failed"):
                adapter.extract()

    def test_timeout_raises_ingestion_error(self):
        """Request timeout raises IngestionError."""
        import requests as req

        with patch("src.ingestion.api_ingestion.requests.get",
                   side_effect=req.exceptions.Timeout("timed out")):
            adapter = APIIngestion(url="http://slow.example.com/api", timeout=1)
            with pytest.raises(IngestionError, match="timed out"):
                adapter.extract()

    def test_missing_records_key_raises_ingestion_error(self):
        """JSON without 'records' key raises IngestionError."""
        mock_response = MagicMock()
        mock_response.status_code = 200
        mock_response.json.return_value = {"dataset": "test"}

        with patch("src.ingestion.api_ingestion.requests.get", return_value=mock_response):
            adapter = APIIngestion(url="http://test.example.com/api/data")
            with pytest.raises(IngestionError, match="missing"):
                adapter.extract()


