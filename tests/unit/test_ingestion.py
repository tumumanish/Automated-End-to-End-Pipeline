class TestCSVIngestion:
    """Tests for CSVIngestion."""

    def test_extract_valid_csv(self, valid_csv_path):
        """CSV with valid data returns a non-empty DataFrame."""
        adapter = CSVIngestion(file_path=valid_csv_path)
        df = adapter.extract()

        assert isinstance(df, pd.DataFrame)
        assert len(df) > 0
        assert "transaction_id" in df.columns

    def test_source_type(self, valid_csv_path):
        """source_type property returns 'csv'."""
        adapter = CSVIngestion(file_path=valid_csv_path)
        assert adapter.source_type == "csv"

    def test_source_name(self, valid_csv_path):
        """source_name returns the file path."""
        adapter = CSVIngestion(file_path=valid_csv_path)
        assert str(valid_csv_path) in adapter.source_name

    def test_file_not_found_raises_ingestion_error(self, nonexistent_path):
        """Missing file raises IngestionError."""
        adapter = CSVIngestion(file_path=nonexistent_path)
        with pytest.raises(IngestionError, match="not found"):
            adapter.extract()

    def test_extract_returns_correct_columns(self, valid_csv_path):
        """Extracted DataFrame has expected columns."""
        adapter = CSVIngestion(file_path=valid_csv_path)
        df = adapter.extract()
        expected_cols = {"transaction_id", "customer_id", "product_id",
                         "transaction_date", "quantity", "unit_price",
                         "total_amount", "location"}
        assert expected_cols.issubset(set(df.columns))


