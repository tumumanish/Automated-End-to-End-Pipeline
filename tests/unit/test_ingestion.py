class TestIngestionFactory:
    """Tests for ingestion_factory."""

    def test_create_csv_adapter(self, valid_csv_path):
        """Factory returns a CSVIngestion for source_type='csv'."""
        adapter = create_ingestion("csv", file_path=valid_csv_path)
        assert isinstance(adapter, CSVIngestion)
        assert adapter.source_type == "csv"

    def test_create_excel_adapter(self, valid_excel_path):
        """Factory returns an ExcelIngestion for source_type='excel'."""
        adapter = create_ingestion("excel", file_path=valid_excel_path)
        assert isinstance(adapter, ExcelIngestion)
        assert adapter.source_type == "excel"

    def test_create_api_adapter(self):
        """Factory returns an APIIngestion for source_type='api'."""
        adapter = create_ingestion("api", url="http://test.example.com/api")
        assert isinstance(adapter, APIIngestion)
        assert adapter.source_type == "api"

    def test_unsupported_source_raises_error(self):
        """Unknown source type raises IngestionError."""
        with pytest.raises(IngestionError, match="Unsupported"):
            create_ingestion("ftp", path="/data")

    def test_list_supported_sources(self):
        """list_supported_sources returns known types."""
        sources = list_supported_sources()
        assert "csv" in sources
        assert "excel" in sources
        assert "api" in sources
        assert "database" in sources

    def test_case_insensitive(self, valid_csv_path):
        """Factory handles upper/mixed case source types."""
        adapter = create_ingestion("CSV", file_path=valid_csv_path)
        assert isinstance(adapter, CSVIngestion)
