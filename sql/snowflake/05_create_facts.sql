CREATE TABLE IF NOT EXISTS WAREHOUSE.FACT_TRANSACTIONS (
    TRANSACTION_KEY NUMBER AUTOINCREMENT,
    DATE_KEY INTEGER NOT NULL,
    CUSTOMER_KEY NUMBER NOT NULL,
    PRODUCT_KEY NUMBER NOT NULL,
    LOCATION_KEY NUMBER NOT NULL,
    TRANSACTION_ID VARCHAR(255) NOT NULL,
    QUANTITY INTEGER NOT NULL,
    UNIT_PRICE NUMBER(15, 2) NOT NULL,
    AMOUNT NUMBER(15, 2) NOT NULL,
    STATUS VARCHAR(50) DEFAULT 'completed',
    BATCH_ID VARCHAR(100),
    LOADED_TIMESTAMP TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT FK_FACT_DATE FOREIGN KEY (DATE_KEY) REFERENCES WAREHOUSE.DIM_DATE(DATE_KEY),
    CONSTRAINT FK_FACT_CUST FOREIGN KEY (CUSTOMER_KEY) REFERENCES WAREHOUSE.DIM_CUSTOMER(CUSTOMER_KEY),
    CONSTRAINT FK_FACT_PROD FOREIGN KEY (PRODUCT_KEY) REFERENCES WAREHOUSE.DIM_PRODUCT(PRODUCT_KEY),
    CONSTRAINT FK_FACT_LOC  FOREIGN KEY (LOCATION_KEY) REFERENCES WAREHOUSE.DIM_LOCATION(LOCATION_KEY)
);
