CREATE TABLE IF NOT EXISTS WAREHOUSE.DIM_DATE (
    DATE_KEY INTEGER PRIMARY KEY,
    FULL_DATE DATE NOT NULL,
    DAY_OF_WEEK INTEGER NOT NULL,
    DAY_NAME VARCHAR(20) NOT NULL,
    DAY_OF_MONTH INTEGER NOT NULL,
    DAY_OF_YEAR INTEGER NOT NULL,
    WEEK_OF_YEAR INTEGER NOT NULL,
    MONTH INTEGER NOT NULL,
    MONTH_NAME VARCHAR(20) NOT NULL,
    QUARTER INTEGER NOT NULL,
    YEAR INTEGER NOT NULL,
    IS_WEEKEND BOOLEAN NOT NULL DEFAULT FALSE,
    IS_HOLIDAY BOOLEAN NOT NULL DEFAULT FALSE,
    FISCAL_QUARTER INTEGER,
    FISCAL_YEAR INTEGER
);

CREATE TABLE IF NOT EXISTS WAREHOUSE.DIM_CUSTOMER (
    CUSTOMER_KEY NUMBER AUTOINCREMENT,
    CUSTOMER_ID VARCHAR(255) NOT NULL,
    CUSTOMER_NAME VARCHAR(255),
    SEGMENT VARCHAR(100),
    REGION VARCHAR(100),
    VALID_FROM TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    VALID_TO TIMESTAMP_TZ,
    IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS WAREHOUSE.DIM_PRODUCT (
    PRODUCT_KEY NUMBER AUTOINCREMENT,
    PRODUCT_ID VARCHAR(255) NOT NULL,
    PRODUCT_NAME VARCHAR(255),
    CATEGORY VARCHAR(100),
    SUBCATEGORY VARCHAR(100),
    UNIT_PRICE NUMBER(15, 2),
    VALID_FROM TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    VALID_TO TIMESTAMP_TZ,
    IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS WAREHOUSE.DIM_LOCATION (
    LOCATION_KEY NUMBER AUTOINCREMENT,
    LOCATION_ID VARCHAR(255) NOT NULL,
    LOCATION_NAME VARCHAR(255) NOT NULL,
    CITY VARCHAR(100),
    STATE VARCHAR(100),
    COUNTRY VARCHAR(100) DEFAULT 'India',
    REGION VARCHAR(100)
);
