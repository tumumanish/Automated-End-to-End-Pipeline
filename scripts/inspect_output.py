#!/usr/bin/env python
"""
Script: inspect_output.py
Purpose:
    Display and format all outputs generated by the Automated Data Pipeline:
    - Latest Curated Parquet Dataset (Enriched Columns, Dimensions, Sample Records)
    - Data Quality Scorecards (Freshness, Completeness, Accuracy, Adherence)
    - Full End-to-End Lineage Events & Schema Snapshots
    - Pipeline Execution Metrics & Performance
"""

import os
import sys
import glob
import json
from pathlib import Path
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

def print_separator(title=""):
    print("\n" + "=" * 75)
    if title:
        print(f"  {title}")
        print("=" * 75)

def inspect_latest_execution():
    print_separator("1. LATEST PIPELINE EXECUTION METRIC")
    metric_files = sorted(glob.glob(str(PROJECT_ROOT / "logs" / "pipeline" / "*_metrics.json")), key=os.path.getmtime, reverse=True)
    if not metric_files:
        print("No execution metrics found in logs/pipeline/")
        return
    latest = metric_files[0]
    with open(latest, "r", encoding="utf-8") as f:
        data = json.load(f)
    print(f"File       : {Path(latest).name}")
    print(f"Execution  : {data.get('execution_id')} ({data.get('pipeline_name')})")
    print(f"Status     : {data.get('status')}")
    print(f"Duration   : {data.get('duration_seconds')} seconds")
    print(f"Records    : {data.get('records_extracted')} extracted -> {data.get('records_valid')} valid -> {data.get('records_transformed')} transformed")
    print(f"Timestamp  : {data.get('started_at')}")

def inspect_quality_metrics():
    print_separator("2. DATA QUALITY SCORECARD")
    quality_files = sorted(glob.glob(str(PROJECT_ROOT / "logs" / "validation" / "*_quality.json")), key=os.path.getmtime, reverse=True)
    if not quality_files:
        print("No quality metrics found in logs/validation/")
        return
    latest = quality_files[0]
    with open(latest, "r", encoding="utf-8") as f:
        q = json.load(f)
    print(f"Batch ID             : {q.get('batch_id')}")
    print(f"Overall Quality Score: {q.get('overall_score', 0):.1f}%")
    print(f"  * Freshness        : {q.get('freshness_score', 0):.1f}%")
    print(f"  * Completeness     : {q.get('completeness_score', 0):.1f}%")
    print(f"  * Accuracy         : {q.get('accuracy_score', 0):.1f}%")
    print(f"  * Contract Rules   : {q.get('contract_adherence_score', 0):.1f}%")
    print(f"Valid / Quarantined  : {q.get('valid_count')} valid / {q.get('quarantined_count', 0)} quarantined")

def inspect_lineage():
    print_separator("3. END-TO-END DATA LINEAGE FLOW")
    lineage_files = sorted(glob.glob(str(PROJECT_ROOT / "logs" / "lineage" / "*_lineage.json")), key=os.path.getmtime, reverse=True)
    if not lineage_files:
        print("No lineage files found in logs/lineage/")
        return
    latest = lineage_files[0]
    with open(latest, "r", encoding="utf-8") as f:
        l = json.load(f)
    print(f"Batch: {l.get('batch_id')} | Pipeline: {l.get('pipeline')} | Total Stages: {l.get('event_count')}")
    print("-" * 75)
    print(f"{'STAGE':<25} | {'INPUT':<7} | {'OUTPUT':<7} | {'STAGE DETAILS'}")
    print("-" * 75)
    for evt in l.get("events", []):
        stage = evt.get("stage")
        inp = str(evt.get("input_record_count", 0))
        out = str(evt.get("output_record_count", 0))
        meta = evt.get("metadata", {})
        details = ""
        if "raw_path" in meta:
            details = "Saved immutable raw CSV"
        elif "curated_path" in meta:
            details = "Saved curated Parquet lakehouse"
        elif "transformations" in meta:
            details = f"{len(meta['transformations'])} transforms (clean, enrich, cast)"
        elif "valid" in meta:
            details = f"Validation: {meta.get('status')} ({meta.get('valid')} passed)"
        elif "new_records" in meta:
            details = f"SCD2: {meta.get('new_records')} new records tracked"
        elif "source_name" in meta:
            details = f"Source: {Path(meta['source_name']).name}"
        print(f"{stage:<25} | {inp:<7} | {out:<7} | {details}")

def inspect_curated_parquet():
    print_separator("4. CURATED ANALYTICS DATASET (PARQUET LAKEHOUSE)")
    parquet_files = sorted(glob.glob(str(PROJECT_ROOT / "data" / "curated" / "transactions" / "*.parquet")), key=os.path.getmtime, reverse=True)
    if not parquet_files:
        print("No Parquet files found in data/curated/transactions/")
        return
    latest = parquet_files[0]
    df = pd.read_parquet(latest)
    print(f"Curated Parquet Path : {latest}")
    print(f"Dataset Dimensions   : {df.shape[0]} Rows x {df.shape[1]} Columns")
    print(f"All Columns          : {', '.join(df.columns.tolist())}")
    print("\nFirst 3 Transformed & Enriched Records:")
    display_cols = [c for c in ['transaction_id', 'customer_id', 'total_amount', 'calculated_total', 'is_high_value', 'discount_amount', 'transaction_day_of_week'] if c in df.columns]
    print(df[display_cols].head(3).to_string(index=False))

def inspect_star_schema():
    print_separator("5. STAR SCHEMA DATA WAREHOUSE (FACTS & DIMENSIONS)")
    from src.storage.postgres.pg_loader import PostgresLoader
    loader = PostgresLoader()
    tables = {
        "dim_date": "warehouse",
        "dim_customer": "warehouse",
        "dim_product": "warehouse",
        "dim_location": "warehouse",
        "fact_transactions": "warehouse",
        "stg_transactions": "staging",
    }
    for tbl, schema in tables.items():
        try:
            cnt = loader.table_row_count(tbl, schema)
            print(f"  * {schema}.{tbl:<20} : {cnt:,} rows")
        except Exception:
            print(f"  * {schema}.{tbl:<20} : 0 rows (not initialized)")

    # Sample from fact table
    try:
        facts = loader.query("SELECT transaction_id, date_key, customer_key, product_key, location_key, quantity, amount FROM warehouse.fact_transactions LIMIT 3")
        if not facts.empty:
            print("\nSample Fact Transactions:")
            print(facts.to_string(index=False))
    except Exception:
        pass

def inspect_analytical_views():
    print_separator("6. BUSINESS INTELLIGENCE ANALYTICAL VIEWS")
    from src.warehouse.views.view_manager import ViewManager
    vm = ViewManager()
    views = vm.list_views()
    print(f"Active Materialized Analytical Views ({len(views)}):")
    for v in views:
        print(f"  - {v}")

    # Display Daily Sales
    try:
        daily = vm.query_view("v_daily_sales", limit=3)
        if not daily.empty:
            print("\nTop 3 Rows from v_daily_sales:")
            print(daily[['full_date', 'total_sales', 'total_quantity', 'transaction_count', 'avg_transaction_value']].head(3).to_string(index=False))
    except Exception:
        pass

    # Display Product Performance
    try:
        prod = vm.query_view("v_product_performance", limit=3)
        if not prod.empty:
            print("\nTop 3 Products from v_product_performance:")
            print(prod[['product_id', 'product_name', 'category', 'total_revenue', 'units_sold']].head(3).to_string(index=False))
    except Exception:
        pass

def main():
    print("=" * 75)
    print("  AUTOMATED DATA PIPELINE — SYSTEM OUTPUT INSPECTOR")
    print("=" * 75)
    inspect_latest_execution()
    inspect_quality_metrics()
    inspect_lineage()
    inspect_curated_parquet()
    inspect_star_schema()
    inspect_analytical_views()
    print_separator("7. WEB DASHBOARD & REST API")
    print("To view these outputs in the interactive visual interface:")
    print("  1. Run   : python -m uvicorn api.main:app --port 8000")
    print("  2. Open  : http://localhost:8000/       (Interactive Web Control Center)")
    print("  3. Open  : http://localhost:8000/docs   (Swagger REST API Explorer)")
    print("=" * 75 + "\n")

if __name__ == "__main__":
    main()
